# Icons that must render as solid fills even though they are built from
# rect/polygon primitives (outline would look wrong).
_FILL_OVERRIDES = {"play", "pause", "crown", "quote", "graduation-cap", "paper-plane"}


def _primitives_xml(primitives, attrs):
    """Render primitives as SVG markup strings (24x24 coordinate space)."""
    out = []
    for p in primitives:
        kind = p[0]
        args = p[1:]
        if kind == "path":
            out.append(f'<path d="{args[0]}" {attrs}/>')
        elif kind == "line":
            out.append(
                f'<line x1="{args[0]}" y1="{args[1]}" x2="{args[2]}" y2="{args[3]}" {attrs}/>')
        elif kind == "rect":
            out.append(
                f'<rect x="{args[0]}" y="{args[1]}" width="{args[2]}" height="{args[3]}" {attrs}/>')
        elif kind == "circle":
            out.append(f'<circle cx="{args[0]}" cy="{args[1]}" r="{args[2]}" {attrs}/>')
        elif kind == "polygon":
            out.append(f'<polygon points="{args[0]}" {attrs}/>')
        elif kind == "ellipse":
            out.append(
                f'<ellipse cx="{args[0]}" cy="{args[1]}" rx="{args[2]}" ry="{args[3]}" {attrs}/>')
    return "".join(out)


def icon_mode(icon_id):
    """'fill' or 'stroke' for the icon's primary rendering."""
    if icon_id in _FILL_OVERRIDES:
        return "fill"
    prims = ICONS.get(icon_id, [])
    return "fill" if prims and all(p[0] == "path" for p in prims) else "stroke"


def icon_svg(name, color="#1F2937", size=24):
    """Return an SVG document string for the icon, colored with `color`."""
    icon_id = normalize(name) or "circle-dot"
    prims = ICONS.get(icon_id, ICONS["circle-dot"])
    if icon_mode(icon_id) == "fill":
        attrs = f'fill="{color}"'
    else:
        attrs = ('fill="none" stroke="%s" stroke-width="2" '
                 'stroke-linecap="round" stroke-linejoin="round"' % color)
    inner = _primitives_xml(prims, attrs)
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" '
        f'viewBox="0 0 24 24">{inner}</svg>'
    )


def normalize(name):
    """'fas:house' / 'fa-solid house' -> canonical icon id (or None)."""
    if not name:
        return None
    for prefix in _STYLE_PREFIXES:
        if name.startswith(prefix + ":"):
            name = name[len(prefix) + 1:]
            break
        if name.startswith(prefix + " "):
            name = name[len(prefix) + 1:]
            break
    name = name.strip().lower()
    while name.startswith("fa-"):
        name = name[3:]
    if name in ICONS:
        return name
    if name in _ALIASES:
        return _ALIASES[name]
    # kebab-case fallback: try progressively removing suffix words
    parts = name.split("-")
    for i in range(len(parts) - 1, 0, -1):
        cand = "-".join(parts[:i])
        if cand in ICONS or cand in _ALIASES:
            return _ALIASES.get(cand, cand)
    return None
